"""Render ``results/RESULTS.md`` from the JSON files the CLI writes."""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

SIMULATOR_NOTE = (
    "> **All `qant` numbers below come from the Q.ANT toolkit's `cpu-backend` simulator, "
    "a noise-free bfloat16 emulation running on the host CPU. They are not hardware "
    "measurements and say nothing about NPU speed or energy.**"
)


def _table(header: Sequence[str], rows: Sequence[Sequence[Any]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def render_results(results: Path) -> str:
    bench = _load(results / "benchmark.json")
    parts = ["# Results", "", "Generated by `photonic-poc reproduce`. Do not edit by hand.", ""]
    parts += [SIMULATOR_NOTE, ""]
    if bench:
        env = bench["environment"]
        parts += ["## Environment", ""]
        parts += [f"- `{k}`: {v}" for k, v in env.items()] + [""]
        parts += _quality(bench) + _by_kind(bench) + _latency(bench)
    seeds = _load(results / "seed_study.json")
    if seeds:
        parts += _seed_study(seeds)
    noise = _load(results / "noise_sweep.json")
    if noise:
        parts += _noise(noise)
    ops = _load(results / "op_numerics.json")
    if ops:
        parts += _ops(ops)
    training = _load(results / "training.json")
    if training:
        rows = [[k, v["best_epoch"], f"{v['val']['f1']:.4f}"] for k, v in training.items()]
        parts += ["## Training", "", _table(["model", "best epoch", "val F1"], rows), ""]
    return "\n".join(parts)


def _quality(bench: dict[str, Any]) -> list[str]:
    rows = []
    for r in bench["rows"]:
        m, a = r["metrics"], r["agreement_vs_fp32"]
        rows.append(
            [
                r["model"],
                r["parameters"],
                r["backend"],
                f"{m['precision']:.4f}",
                f"{m['recall']:.4f}",
                f"{m['f1']:.4f}",
                f"{m['roc_auc']:.4f}",
                f"{100 * a['rel_rms_diff']:.2f}%",
                f"{a['max_abs_diff']:.3f}",
                a["decision_flips"],
            ]
        )
    header = ["model", "params", "backend", "precision", "recall", "F1", "ROC AUC",
              "rel. RMS Δlogit vs fp32", "max abs Δlogit", "decision flips"]  # fmt: skip
    n = int(bench["rows"][0]["latency"]["full_batch_size"]) if bench["rows"] else 0
    intro = f"Test split, {n} pairs, threshold at logit 0 (probability 0.5)."
    return [
        "## Matching quality and agreement with float32",
        "",
        intro,
        "",
        _table(header, rows),
        "",
    ]


def _seed_study(rows: list[dict[str, Any]]) -> list[str]:
    def ms(s: dict[str, float]) -> str:
        return f"{s['mean']:.4f} ± {s['std']:.4f}"

    has_qant = "f1_qant" in rows[0]
    header = ["model", "train noise σ", "F1 torch-fp32"]
    header += ["F1 qant", "max abs ΔF1 (qant vs fp32)", "flips mean / max"] if has_qant else []
    header += [f"F1 under assumed noise σ={rows[0]['eval_noise']:g}"]
    table = []
    for r in rows:
        row = [r["model"], f"{r['train_noise']:g}", ms(r["f1_fp32"])]
        if has_qant:
            flips = r["flips"]
            row += [ms(r["f1_qant"]), f"{r['max_abs_f1_delta']:.4f}"]
            row += [f"{flips['mean']:.1f} / {flips['max']:.0f}"]
        table.append([*row, ms(r["f1_noisy"])])
    note = (
        f"Each variant retrained with {rows[0]['seeds']} seeds (mean ± std over seeds); "
        "test split as above. Differences smaller than the seed spread are not meaningful."
    )
    return ["## Seed study", "", note, "", _table(header, table), ""]


def _by_kind(bench: dict[str, Any]) -> list[str]:
    rows = [r for r in bench["rows"] if "accuracy_by_kind" in r]
    if not rows:
        return []
    kinds = sorted(rows[0]["accuracy_by_kind"])
    table = [
        [r["model"], r["backend"], *(f"{r['accuracy_by_kind'][k]:.3f}" for k in kinds)]
        for r in rows
    ]
    return ["## Accuracy by pair kind", "", _table(["model", "backend", *kinds], table), ""]


def _latency(bench: dict[str, Any]) -> list[str]:
    rows = [
        [
            r["model"],
            r["backend"],
            f"{r['latency']['batch1_ms']:.3f}",
            f"{r['latency']['us_per_pair']:.2f}",
        ]
        for r in bench["rows"]
    ]
    note = (
        "Median host wall-clock time on the machine listed above. For `qant` this is the cost "
        "of the CPU emulation plus Python/FFI overhead, **not** NPU latency."
    )
    return [
        "## Host latency",
        "",
        note,
        "",
        _table(["model", "backend", "batch 1 [ms]", "full batch [µs/pair]"], rows),
        "",
    ]


def _noise(noise: list[dict[str, Any]]) -> list[str]:
    stds = sorted({r["noise_std"] for r in noise})
    models = list(dict.fromkeys(r["model"] for r in noise))
    cell = {(r["model"], r["noise_std"]): f"{r['f1_mean']:.4f} ± {r['f1_std']:.4f}" for r in noise}
    rows = [[m, *(cell.get((m, s), "") for s in stds)] for m in models]
    note = (
        "Test F1 under an **assumed** noise model: additive Gaussian noise with standard deviation "
        "σ at the output of every NPU-executed layer (Linear, FourierKAN), float32 otherwise, "
        "mean ± std over seeds. This is a robustness probe, not a model of Q.ANT hardware noise."
    )
    return [
        "## Robustness to assumed analog noise",
        "",
        note,
        "",
        _table(["model", *(f"σ={s:g}" for s in stds)], rows),
        "",
    ]


def _ops(ops: dict[str, Any]) -> list[str]:
    def fmt(e: dict[str, float]) -> str:
        return f"{100 * e['rel_rms_err']:.3f}% / {e['max_abs_err']:.4f}"

    lin = [[r["fan_in"], fmt(r["toolkit"]), fmt(r["torch_bf16"])] for r in ops["linear"]]
    kan = [
        [
            r["fan_in"],
            r["terms_per_output"],
            fmt(r["toolkit"]),
            fmt(r["emulated_bf16_terms_exact_sum"]),
            fmt(r["torch_bf16"]),
        ]
        for r in ops["kan"]
    ]
    p = ops["periodic"]
    note = (
        "Relative RMS error / max absolute error against float64 computed on the same "
        "bf16-rounded inputs (so input quantisation is excluded)."
    )
    return [
        "## Operation-level numerics of the toolkit",
        "",
        note,
        "",
        "### `ai.linear_fprop` (64 outputs, batch 256)",
        "",
        _table(["fan-in", "toolkit simulator", "torch bf16"], lin),
        "",
        "### `ai.calc_kan_layer_fprop` (16 outputs, grid 4, batch 64)",
        "",
        _table(
            [
                "fan-in",
                "terms per output",
                "toolkit simulator",
                "toolkit terms, exact sum (emulated)",
                "torch bf16",
            ],
            kan,
        ),
        "",
        f"`native.calc_scaled_periodic_nl_fprop` vs exact cosine on [-4π, 4π] "
        f"({p['points']} points): relative RMS {100 * p['rel_rms_err']:.3f}%, "
        f"max abs {p['max_abs_err']:.4f}. The simulator uses an exact cosine in bf16; "
        "hardware evaluates its own cosine-like `tcos`.",
        "",
    ]
